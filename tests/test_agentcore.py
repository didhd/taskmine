def blob_sha(data: bytes) -> str:
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


class VendoredHarness(unittest.TestCase):
    def test_pr120_files_are_byte_identical_to_upstream(self):
        root = Path(ac.__file__).parent / "pr120"
        files = {str(p.relative_to(root)) for p in root.rglob("*") if p.is_file() and "__pycache__" not in p.parts}
        self.assertEqual(files, set(PR120_BLOBS), "pr120/ holds exactly the upstream files")
        for rel, want in PR120_BLOBS.items():
            self.assertEqual(blob_sha((root / rel).read_bytes()), want, rel)

    def test_scripts_stay_executable(self):
        root = Path(ac.__file__).parent / "pr120"
        for rel in ("image/start.sh", "image/as-agent", "harbor_env/image/as-agent-open",
                    "harbor_env/image/as-grader", "harbor_env/image/record-baseline.sh"):
            self.assertTrue(os.access(root / rel, os.X_OK), rel)


class Rewrites(unittest.TestCase):
    def test_base_image_moves_official_images_to_the_ecr_public_mirror(self):
        d = "@sha256:" + "a" * 64
        self.assertEqual(ac.base_image("node:24-bookworm" + d), "public.ecr.aws/docker/library/node:24-bookworm" + d)
        self.assertEqual(ac.base_image("python:3.12-bookworm"), "public.ecr.aws/docker/library/python:3.12-bookworm")
        self.assertEqual(ac.base_image("docker.io/library/golang:1.24"), "public.ecr.aws/docker/library/golang:1.24")
        for other in ("ghcr.io/acme/base:1", "acme/base:1", "public.ecr.aws/docker/library/node:24",
                      "123456789012.dkr.ecr.us-east-1.amazonaws.com/x:1"):
            self.assertEqual(ac.base_image(other), other)

    def test_dockerfile_keeps_every_line_and_appends_the_variant(self):
        out = ac.dockerfile(DOCKERFILE)
        self.assertIn("FROM public.ecr.aws/docker/library/node:24-bookworm@sha256:6b33b0be", out)
        for line in DOCKERFILE.splitlines()[2:]:
            self.assertIn(line, out)
        self.assertTrue(out.rstrip().endswith("chmod -R a+rX /opt/uv-python"))
        self.assertIn("chown -R 2000:2000 /app", out)
        for pin in (ac.CLAUDE_CODE, ac.CODEX, ac.STRANDS):
            self.assertIn(pin, out)

    def test_task_toml_allowlists_bedrock_for_the_agent_and_nothing_for_the_grader(self):
        doc = tomllib.loads(ac.task_toml(TASK_TOML))
        self.assertEqual(doc["environment"]["network_mode"], "allowlist")
        self.assertEqual(doc["environment"]["allowed_hosts"], list(ac.MODEL_HOSTS))
        self.assertEqual(doc["verifier"]["network_mode"], "no-network")
        before = tomllib.loads(TASK_TOML)
        self.assertEqual(doc["metadata"], before["metadata"])
        self.assertEqual(doc["agent"], before["agent"])
        self.assertEqual(doc["verifier"]["timeout_sec"], 1200.0)
        self.assertEqual(doc["environment"]["memory_mb"], 6144)

    def test_prepare_rewrites_two_files_and_links_the_rest(self):
        with tempfile.TemporaryDirectory() as d:
            src, dest = Path(d) / "tasks", Path(d) / "out"
            t = src / "pilot-pr7"
            (t / "environment" / "deps").mkdir(parents=True)
            (t / "tests").mkdir()
            (t / "task.toml").write_text(TASK_TOML)
            (t / "environment" / "Dockerfile").write_text(DOCKERFILE)
            (t / "environment" / "deps" / "Dockerfile").write_text("not the task's Dockerfile\n")
            (t / "environment" / "repo.tar.gz").write_bytes(b"\x1f\x8b fake")
            (t / "tests" / "test.sh").write_text("#!/bin/bash\n")
            (src / "notes.txt").write_text("not a task\n")
            ac.prepare(src, dest)
            o = dest / "pilot-pr7"
            self.assertEqual(sorted(p.name for p in dest.iterdir()), ["pilot-pr7"])
            self.assertIn("allowlist", (o / "task.toml").read_text())
            self.assertIn("public.ecr.aws", (o / "environment" / "Dockerfile").read_text())
            self.assertEqual((o / "environment" / "deps" / "Dockerfile").read_text(), "not the task's Dockerfile\n")
            self.assertEqual(os.stat(o / "environment" / "repo.tar.gz").st_ino, os.stat(t / "environment" / "repo.tar.gz").st_ino)
            self.assertEqual((t / "task.toml").read_text(), TASK_TOML, "the source task is never changed")
            ac.prepare(src, dest)  # a second run starts clean
            self.assertTrue((o / "task.toml").exists())


class Flags(unittest.TestCase):
    def agent(self, kind, model="us.openai.gpt-6.1-terra", **kw):
        return {"name": f"{kind}-x", "agent": kind, "provider": "bedrock", "model": model, **kw}

    def test_codex_uses_the_bare_mantle_model_id(self):
        self.assertEqual(ac.codex_model("us.openai.gpt-6.1-terra"), "openai.gpt-6.1-terra")
        self.assertEqual(ac.codex_model("openai.gpt-6-sol"), "openai.gpt-6-sol")
        args = ac.harbor_args(self.agent("codex"), "/tmp/p")
        self.assertEqual(args[args.index("-m") + 1], "openai.gpt-6.1-terra")
        self.assertIn("config=" + str(Path("/tmp/p/agentcore/harness/codex-bedrock.toml").resolve()), args)

    def test_every_harness_skips_install_and_gets_no_credentials(self):
        for kind, model in (("claude-code", "us.anthropic.claude-sonnet-5-5"), ("codex", "us.openai.gpt-6.1-terra"),
                            ("opencode", "us.openai.gpt-6.1-terra"), ("strands", "us.openai.gpt-6.1-terra")):
            args = ac.harbor_args(self.agent(kind, model), "/tmp/p")
            self.assertIn("skip_install=true", args, kind)
            self.assertIn(f"AWS_REGION={ac.REGION}", args, kind)
            joined = " ".join(args)
            for secret in ("AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_SESSION_TOKEN", "AWS_BEARER_TOKEN"):
                self.assertNotIn(secret, joined, kind)

    def test_claude_code_points_its_small_model_at_the_same_model(self):
        m = "us.anthropic.claude-sonnet-5-5"
        args = ac.harbor_args(self.agent("claude-code", m), "/tmp/p")
        self.assertIn("CLAUDE_CODE_USE_BEDROCK=1", args)
        self.assertIn(f"ANTHROPIC_DEFAULT_HAIKU_MODEL={m}", args)
        self.assertIn(f"ANTHROPIC_SMALL_FAST_MODEL={m}", args)

    def test_opencode_and_strands_use_bedrock_provider_ids(self):
        oc = ac.harbor_args(self.agent("opencode"), "/tmp/p")
        self.assertEqual(oc[oc.index("-m") + 1], "amazon-bedrock/us.openai.gpt-6.1-terra")
        cfg = json.loads(next(x for x in oc if x.startswith("opencode_config=")).split("=", 1)[1])
        self.assertEqual(cfg["small_model"], "amazon-bedrock/us.openai.gpt-6.1-terra")
        st = ac.harbor_args(self.agent("strands"), "/tmp/p")
        self.assertEqual(st[st.index("-m") + 1], "amazon-bedrock/us.openai.gpt-6.1-terra")

    def test_reference_agents(self):
        self.assertEqual(ac.harbor_args({"name": "oracle", "agent": "oracle"}, "/tmp/p"), ["-a", "oracle"])
        self.assertEqual(ac.harbor_args({"name": "nop", "agent": "nop"}, "/tmp/p"), ["-a", "nop"])

    def test_agent_models_and_checks(self):
        agents = [self.agent("codex"), self.agent("opencode"), self.agent("claude-code", "us.anthropic.claude-sonnet-5-5"),
                  {"name": "oracle", "agent": "oracle", "provider": "-", "model": "gold patch"}]
        self.assertEqual(ac.agent_models(agents),
                         ("openai.gpt-6.1-terra", ["us.anthropic.claude-sonnet-5-5", "us.openai.gpt-6.1-terra"]))
        ac.check_agents(agents)
        with self.assertRaises(ac.AgentCoreError):
            ac.agent_models([self.agent("codex"), self.agent("codex", "us.openai.gpt-6-sol")])
        with self.assertRaises(ac.AgentCoreError):
            ac.check_agents([self.agent("aider")])
        with self.assertRaises(ac.AgentCoreError):
            ac.check_agents([{**self.agent("claude-code"), "provider": "anthropic"}])

    def test_run_env_drops_bedrock_api_keys(self):
        os.environ["AWS_BEARER_TOKEN_BEDROCK"] = "not-a-real-token"
        try:
            env = ac.run_env("/tmp/p", "V2")
        finally:
            del os.environ["AWS_BEARER_TOKEN_BEDROCK"]
        self.assertNotIn("AWS_BEARER_TOKEN_BEDROCK", env)
        self.assertEqual((env["P2_PREFIX"], env["AWS_REGION"], env["TASKMINE_AC_PLATFORM"]), (ac.PREFIX, ac.REGION, "V2"))
        self.assertTrue(ac.PREFIX.startswith("evals-"), "PR #120's teardown refuses any other prefix")


